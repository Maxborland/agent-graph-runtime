test("writing run uses an isolated worktree and produces an immutable run result", async () => {
  const root = await mkdtemp(join(tmpdir(), "agr-git-transaction-"));
  await exec("git", ["init", "--quiet", "-b", "main"], { cwd: root });
  await exec("git", ["config", "user.email", "test@example.com"], { cwd: root });
  await exec("git", ["config", "user.name", "Test"], { cwd: root });
  await writeFile(join(root, "README.md"), "committed\n");
  await exec("git", ["add", "README.md"], { cwd: root });
  await exec("git", ["commit", "--quiet", "-m", "initial"], { cwd: root });
  const baseCommit = (await exec("git", ["rev-parse", "HEAD"], { cwd: root })).stdout.trim();
  await writeFile(join(root, "README.md"), "personal dirty change\n");
  await writeFile(join(root, "personal.txt"), "keep me\n");

  let executionRoot = "";
  const adapter: AgentAdapter = {
    async execute(request) {
      executionRoot = request.repositoryRoot;
      await writeFile(join(request.repositoryRoot, "generated.txt"), "generated by run\n");
      return {
        handoff: {
          status: "complete",
          summary: "generated file",
          changedFiles: ["generated.txt"],
          verification: [],
          gaps: [],
        },
        stdout: "",
        stderr: "",
        exitCode: 0,
      };
    },
  };
  const graph: GraphDefinition = {
    version: 1,
    run: { id: "git-transaction", objective: "isolate writes", repository: ".", maxConcurrency: 1 },
    nodes: [{
      id: "generate",
      type: "agent",
      executor: "codex",
      prompt: "generate",
      needs: [],
      owns: ["generated.txt"],
      checks: [],
      maxAttempts: 1,
    }],
  };

  try {
    const state = await new GraphRunner(graph, root, { codex: adapter }).run();
    assert.equal(state.status, "completed");
    assert.equal(state.repository.baseCommit, baseCommit);
    assert.match(executionRoot.replaceAll("\\", "/"), /\/\.worktrees\/git-transaction-[0-9a-f]{12}$/);
    assert.equal(await readFile(join(root, "README.md"), "utf8"), "personal dirty change\n");
    assert.equal(await readFile(join(root, "personal.txt"), "utf8"), "keep me\n");
    await assert.rejects(access(join(root, "generated.txt")));
    assert.equal(await readFile(join(executionRoot, "generated.txt"), "utf8"), "generated by run\n");

    const result = JSON.parse(
      await readFile(join(root, ".agent-graph", "runs", graph.run.id, "result.json"), "utf8"),
    ) as { schemaVersion?: number; baseCommit?: string; resultCommit?: string; checkpoints?: unknown[] };
    assert.equal(result.schemaVersion, 1);
    assert.equal(result.baseCommit, baseCommit);
    assert.match(result.resultCommit ?? "", /^[0-9a-f]{40}$/);
    assert.equal(result.checkpoints?.length, 1);
    const acceptedEvidence = Object.values(state.attempts).find((attempt) => attempt.status === "accepted")!.evidence[0]!;
    const evidenceDocument = JSON.parse(
      await readFile(join(root, ".agent-graph", "runs", graph.run.id, acceptedEvidence.localPath), "utf8"),
    ) as { retryBlocked?: boolean };
    assert.equal(evidenceDocument.retryBlocked, false);
    assert.equal(
      (await exec("git", ["show", `${result.resultCommit}:generated.txt`], { cwd: root })).stdout,
      "generated by run\n",
    );
  } finally {
    await rm(root, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
  }
});

test("completed run integrates explicitly and rolls back through a revert commit", async () => {
  const root = await mkdtemp(join(tmpdir(), "agr-git-integrate-"));
  await exec("git", ["init", "--quiet", "-b", "main"], { cwd: root });
  await exec("git", ["config", "user.email", "test@example.com"], { cwd: root });
  await exec("git", ["config", "user.name", "Test"], { cwd: root });
  await writeFile(join(root, "README.md"), "base\n");
  await exec("git", ["add", "README.md"], { cwd: root });
  await exec("git", ["commit", "--quiet", "-m", "initial"], { cwd: root });
  const baseCommit = (await exec("git", ["rev-parse", "HEAD"], { cwd: root })).stdout.trim();
  const adapter: AgentAdapter = {
    async execute(request) {
      await writeFile(join(request.repositoryRoot, "generated.txt"), "integrate me\n");
      return {
        handoff: { status: "complete", summary: "generated", changedFiles: ["generated.txt"], verification: [], gaps: [] },
        stdout: "",
        stderr: "",
        exitCode: 0,
      };
    },
  };
  const graph: GraphDefinition = {
    version: 1,
    run: { id: "integrate-run", objective: "integrate", repository: ".", maxConcurrency: 1 },
    nodes: [{ id: "generate", type: "agent", executor: "codex", prompt: "generate", needs: [], owns: ["generated.txt"], checks: [], maxAttempts: 1 }],
  };

  try {
    const graphPath = join(root, ".agent-graph", "graph.json");
    await mkdir(join(root, ".agent-graph"), { recursive: true });
    await writeFile(graphPath, `${JSON.stringify(graph, null, 2)}\n`, "utf8");
    const completed = await new GraphRunner(graph, root, { codex: adapter }).run();
    const resultCommit = completed.git!.resultCommit!;
    const resultPath = join(root, ".agent-graph", "runs", graph.run.id, "result.json");
    const originalResult = await readFile(resultPath, "utf8");
    const transplanted = JSON.parse(originalResult) as Record<string, unknown>;
    transplanted.repositoryId = join(root, "different-clone");
    const { resultId: _oldResultId, ...transplantedContent } = transplanted;
    transplanted.resultId = `result-${sha256(JSON.stringify(transplantedContent)).slice(0, 24)}`;
    await writeFile(resultPath, `${JSON.stringify(transplanted, null, 2)}\n`);
    await assert.rejects(
      integrateRun(root, graph.run.id, "main", true),
      /run result repository identity does not match/,
    );
    await writeFile(resultPath, originalResult);
    const evidence = Object.values(completed.attempts).flatMap((attempt) => attempt.evidence)[0]!;
    const evidencePath = join(root, ".agent-graph", "runs", graph.run.id, evidence.localPath);
    const originalEvidence = await readFile(evidencePath);
    await writeFile(evidencePath, "tampered bytes");
    await assert.rejects(
      integrateRun(root, graph.run.id, "main", true),
      /failed byte-level integrity verification/,
    );
    await writeFile(evidencePath, originalEvidence);
    await assert.rejects(
      new OperatorControl(graph, root).retry("generate"),
      (error: unknown) => (error as { code?: string }).code === "COMPLETED_RUN_IMMUTABLE",
    );
    const preview = JSON.parse((await exec(
      process.execPath,
      [resolve("dist/src/cli.js"), "integrate", graph.run.id, graphPath, "--target", "main", "--dry-run", "--json"],
      { cwd: root, encoding: "utf8" },
    )).stdout) as Awaited<ReturnType<typeof integrateRun>>;
    assert.equal(preview.mode, "fast-forward");
    assert.equal(preview.mutated, false);
    assert.equal((await exec("git", ["rev-parse", "HEAD"], { cwd: root })).stdout.trim(), baseCommit);

    const integrated = await integrateRun(root, graph.run.id, "main", false);
    assert.equal(integrated.mutated, true);
    assert.equal(integrated.targetAfter, resultCommit);
    assert.equal(await readFile(join(root, "generated.txt"), "utf8"), "integrate me\n");
    await assert.rejects(
      integrateRun(root, graph.run.id, "main", false),
      /already integrated and not rolled back/,
    );
    assert.equal((await new GraphRunner(graph, root, { codex: adapter }).run()).status, "completed");
    const resultBeforeRollback = await readFile(join(root, ".agent-graph", "runs", graph.run.id, "result.json"), "utf8");

    const rollbackPreview = await rollbackRun(root, graph.run.id, true);
    assert.equal(rollbackPreview.mutated, false);
    assert.equal(await readFile(join(root, "generated.txt"), "utf8"), "integrate me\n");
    const rolledBack = await rollbackRun(root, graph.run.id, false);
    assert.equal(rolledBack.mutated, true);
    await assert.rejects(access(join(root, "generated.txt")));
    assert.notEqual((await exec("git", ["rev-parse", "HEAD"], { cwd: root })).stdout.trim(), baseCommit);
    assert.equal(await readFile(join(root, ".agent-graph", "runs", graph.run.id, "result.json"), "utf8"), resultBeforeRollback);
  } finally {
    await rm(root, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
  }
});

test("ownership escape cannot be checkpointed by an automatic retry", async () => {
  const root = await mkdtemp(join(tmpdir(), "agr-git-escape-checkpoint-"));
  await exec("git", ["init", "--quiet", "-b", "main"], { cwd: root });
  await exec("git", ["config", "user.email", "test@example.com"], { cwd: root });
  await exec("git", ["config", "user.name", "Test"], { cwd: root });
  await writeFile(join(root, "README.md"), "base\n");
  await exec("git", ["add", "README.md"], { cwd: root });
  await exec("git", ["commit", "--quiet", "-m", "initial"], { cwd: root });
  let calls = 0;
  const adapter: AgentAdapter = {
    async execute(request) {
      calls += 1;
      if (calls === 1) await writeFile(join(request.repositoryRoot, "escaped.txt"), "rejected\n");
      return {
        handoff: { status: "complete", summary: "done", changedFiles: calls === 1 ? ["escaped.txt"] : [], verification: [], gaps: [] },
        stdout: "",
        stderr: "",
        exitCode: 0,
      };
    },
  };
  const graph: GraphDefinition = {
    version: 1,
    run: { id: "escape-checkpoint", objective: "reject escape", repository: ".", maxConcurrency: 1 },
    nodes: [{ id: "writer", type: "agent", executor: "codex", prompt: "write", needs: [], owns: ["owned.txt"], checks: [], maxAttempts: 2 }],
  };

  try {
    const state = await new GraphRunner(graph, root, { codex: adapter }).run();
    assert.equal(state.status, "needs_attention");
    assert.equal(calls, 1);
    await assert.rejects(access(join(root, ".agent-graph", "runs", graph.run.id, "result.json")));
    await assert.rejects(exec("git", ["show", `${state.git!.runBranch}:escaped.txt`], { cwd: root }));
  } finally {
    await rm(root, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
  }
});

