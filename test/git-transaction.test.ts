test("writing run can chain only from an explicitly selected committed result", async () => {
  const root = await mkdtemp(join(tmpdir(), "agr-git-chain-"));
  await exec("git", ["init", "--quiet", "-b", "main"], { cwd: root });
  await exec("git", ["config", "user.email", "test@example.com"], { cwd: root });
  await exec("git", ["config", "user.name", "Test"], { cwd: root });
  await writeFile(join(root, "README.md"), "base\n");
  await exec("git", ["add", "README.md"], { cwd: root });
  await exec("git", ["commit", "--quiet", "-m", "initial"], { cwd: root });
  const firstGraph: GraphDefinition = {
    version: 1,
    run: { id: "chain-first", objective: "first", repository: ".", maxConcurrency: 1 },
    nodes: [{ id: "first", type: "agent", executor: "codex", prompt: "first", needs: [], owns: ["first.txt"], checks: [], maxAttempts: 1 }],
  };
  const firstAdapter: AgentAdapter = {
    async execute(request) {
      await writeFile(join(request.repositoryRoot, "first.txt"), "first\n");
      return { handoff: { status: "complete", summary: "first", changedFiles: ["first.txt"], verification: [], gaps: [] }, stdout: "", stderr: "", exitCode: 0 };
    },
  };

  try {
    const first = await new GraphRunner(firstGraph, root, { codex: firstAdapter }).run();
    const parentCommit = first.git!.resultCommit!;
    let secondRoot = "";
    const secondGraph: GraphDefinition = {
      version: 1,
      run: { id: "chain-second", objective: "second", repository: ".", maxConcurrency: 1, baseCommit: parentCommit },
      nodes: [{ id: "second", type: "agent", executor: "codex", prompt: "second", needs: [], owns: ["second.txt"], checks: [], maxAttempts: 1 }],
    };
    const secondAdapter: AgentAdapter = {
      async execute(request) {
        secondRoot = request.repositoryRoot;
        assert.equal(await readFile(join(request.repositoryRoot, "first.txt"), "utf8"), "first\n");
        await writeFile(join(request.repositoryRoot, "second.txt"), "second\n");
        return { handoff: { status: "complete", summary: "second", changedFiles: ["second.txt"], verification: [], gaps: [] }, stdout: "", stderr: "", exitCode: 0 };
      },
    };

    const second = await new GraphRunner(secondGraph, root, { codex: secondAdapter }).run();
    assert.equal(second.repository.baseCommit, parentCommit);
    assert.equal(await readFile(join(secondRoot, "first.txt"), "utf8"), "first\n");
  } finally {
    await rm(root, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
  }
});

test("integration dry-run detects a cherry-pick conflict without mutating target", async () => {
  const root = await mkdtemp(join(tmpdir(), "agr-git-conflict-"));
  await exec("git", ["init", "--quiet", "-b", "main"], { cwd: root });
  await exec("git", ["config", "user.email", "test@example.com"], { cwd: root });
  await exec("git", ["config", "user.name", "Test"], { cwd: root });
  await writeFile(join(root, "README.md"), "base\n");
  await exec("git", ["add", "README.md"], { cwd: root });
  await exec("git", ["commit", "--quiet", "-m", "initial"], { cwd: root });
  const graph: GraphDefinition = {
    version: 1,
    run: { id: "conflict-run", objective: "conflict", repository: ".", maxConcurrency: 1 },
    nodes: [{ id: "edit", type: "agent", executor: "codex", prompt: "edit", needs: [], owns: ["README.md"], checks: [], maxAttempts: 1 }],
  };
  const adapter: AgentAdapter = {
    async execute(request) {
      await writeFile(join(request.repositoryRoot, "README.md"), "run change\n");
      return { handoff: { status: "complete", summary: "edit", changedFiles: ["README.md"], verification: [], gaps: [] }, stdout: "", stderr: "", exitCode: 0 };
    },
  };

  try {
    await new GraphRunner(graph, root, { codex: adapter }).run();
    await writeFile(join(root, "README.md"), "target change\n");
    await exec("git", ["add", "README.md"], { cwd: root });
    await exec("git", ["commit", "--quiet", "-m", "target change"], { cwd: root });
    const targetBefore = (await exec("git", ["rev-parse", "HEAD"], { cwd: root })).stdout.trim();

    const preview = await integrateRun(root, graph.run.id, "main", true);
    assert.equal(preview.mode, "conflict");
    assert.equal(preview.mutated, false);
    assert.equal((await exec("git", ["rev-parse", "HEAD"], { cwd: root })).stdout.trim(), targetBefore);
    assert.equal(await readFile(join(root, "README.md"), "utf8"), "target change\n");
  } finally {
    await rm(root, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
  }
});
